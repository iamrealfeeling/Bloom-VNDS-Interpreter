-- fallback when a key is missing in the current language
local function tr(lang, key)
    local t = dict[lang]
    if t and t[key] ~= nil then return t[key] end
    local base = dict.ru
    if base and base[key] ~= nil then return base[key] end
    return key
end

i18n.langs = langs

-- return ordered list of {code=, name=} for the language setting
function i18n.langList()
    local list = {}
    for code, name in pairs(langs) do
        list[#list + 1] = { code = code, name = name }
    end
    table.sort(list, function(a, b) return a.code < b.code end)
    return list
end

function i18n.langName(code)
    return langs[code] or langs.ru
end

-- set current language (validates code)
function i18n.setLanguage(code)
    if langs[code] then i18n.current = code end
    _G.language = i18n.current
end

function i18n.t(key, ...)
    local s = tr(i18n.current or "ru", key)
    local n = select("#", ...)
    if n > 0 then
        return string.format(s, ...)
    end
    return s
end

-- convenience global
_G.t = function(key, ...) return i18n.t(key, ...) end

return i18n
